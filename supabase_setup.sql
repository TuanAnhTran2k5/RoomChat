-- =======================================================
-- BỔ SUNG CHÍNH SÁCH BẢO MẬT UPDATE/DELETE CHO BẢNG ROOMS
-- =======================================================
DROP POLICY IF EXISTS "Chủ phòng được sửa phòng" ON public.rooms;
CREATE POLICY "Chủ phòng được sửa phòng" 
    ON public.rooms FOR UPDATE 
    USING (auth.role() = 'authenticated' AND auth.uid() = created_by);

DROP POLICY IF EXISTS "Chủ phòng được xóa phòng" ON public.rooms;
CREATE POLICY "Chủ phòng được xóa phòng" 
    ON public.rooms FOR DELETE 
    USING (auth.role() = 'authenticated' AND auth.uid() = created_by);


-- =======================================================
-- CẤU HÌNH STORAGE BUCKET CHO AVATARS (LƯU TRỮ ẢNH)
-- =======================================================
-- Tự động chèn tạo bucket 'avatars' công khai nếu chưa tồn tại
INSERT INTO storage.buckets (id, name, public) 
VALUES ('avatars', 'avatars', true)
ON CONFLICT (id) DO NOTHING;

-- Policy 1: Cho phép mọi người đọc ảnh avatar công khai
DROP POLICY IF EXISTS "Cho phép đọc avatar công khai" ON storage.objects;
CREATE POLICY "Cho phép đọc avatar công khai" 
    ON storage.objects FOR SELECT 
    USING (bucket_id = 'avatars');

-- Policy 2: Chỉ cho phép user đã đăng nhập upload ảnh đại diện
DROP POLICY IF EXISTS "Cho phép upload avatar khi đã đăng nhập" ON storage.objects;
CREATE POLICY "Cho phép upload avatar khi đã đăng nhập" 
    ON storage.objects FOR INSERT 
    WITH CHECK (bucket_id = 'avatars' AND auth.role() = 'authenticated');

-- Policy 3: Cho phép user cập nhật/xóa avatar của mình
DROP POLICY IF EXISTS "Cho phép cập nhật avatar chính chủ" ON storage.objects;
CREATE POLICY "Cho phép cập nhật avatar chính chủ" 
    ON storage.objects FOR UPDATE 
    USING (bucket_id = 'avatars' AND auth.role() = 'authenticated');


